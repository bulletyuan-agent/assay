// Builds an index of every result, report and calibration file in this repo, with sha256 pins and GitHub URLs,
// and writes it into the knowledge base repo so lessons there can cite the exact source files.
// Usage: node scripts/gen-report-index.mjs [path/to/knowledge-index.md]   (default: ../.agent/specs/technical/report-index.md)
import { readdirSync, statSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = process.argv[2] || join(REPO_ROOT, '..', '.agent', 'specs', 'technical', 'report-index.md');
const BASE = 'https://github.com/bulletyuan-agent/assay/blob/main/';
const SECTIONS = [
  ['Reports · 评测报告', 'reports', /\.md$/i, /^README\.md$/],
  ['Raw results · 原始结果', 'data/results', /\.json$/i, null],
  ['Calibration · 校准', 'data/calibration', /\.json$/i, null],
  ['Dataset · 数据集', 'data/tasks', /\.json$/i, null],
];

function walk(dir, out = []) {
  if (!existsSync(dir)) return out;
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) { if (n !== 'fixtures') walk(p, out); } else out.push(p);
  }
  return out;
}
let head = 'unknown';
try { head = execFileSync('git', ['-C', REPO_ROOT, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a repo */ }

const lines = [
  '# Report index · 子项目报告原文件索引', '',
  '> Generated by `assay/scripts/gen-report-index.mjs`. Do not edit by hand. 自动生成,勿手改。',
  '> Source of truth lives in the sub-project repo `assay/` (public). This knowledge base cites those files, it does not copy them.',
  `> Generated against assay commit \`${head}\` at ${new Date().toISOString()}.`, '',
  '**Rule · 规则**: when a lesson, calibration conclusion or method change is recorded here, cite the file below by path and sha256, and log it with `mf session log --evidence assay/<path>`. If the sha256 no longer matches, the conclusion must be rechecked.', '',
];
for (const [title, dir, include, exclude] of SECTIONS) {
  const files = walk(join(REPO_ROOT, dir)).filter((f) => include.test(f) && !(exclude && exclude.test(f.split('/').pop()))).sort();
  lines.push(`## ${title}`, '');
  if (!files.length) { lines.push('_None yet. 暂无。_', ''); continue; }
  lines.push('| File | sha256 (12) | Link |', '| --- | --- | --- |');
  for (const f of files) {
    const rel = relative(REPO_ROOT, f);
    const sha = createHash('sha256').update(readFileSync(f)).digest('hex').slice(0, 12);
    lines.push(`| \`assay/${rel}\` | \`${sha}\` | [open](${BASE}${rel}) |`);
  }
  lines.push('');
}
writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${OUT}`);
